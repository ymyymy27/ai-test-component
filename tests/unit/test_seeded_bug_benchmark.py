class _DemoHandler(BaseHTTPRequestHandler):
    def log_message(self, format: str, *args: object) -> None:
        return

    def _send_json(self, code: int, body: dict[str, Any]) -> None:
        raw = json.dumps(body, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self) -> None:
        if self.path == "/health":
            self._send_json(200, {"status": "ok"})
            return
        if self.path == "/calc":
            # Bug 1：故意写错计算结果（预期 6，实际 5）
            self._send_json(200, {"value": 5})
            return
        if self.path == "/crash":
            # Bug 2：接口未捕获异常返回 500
            self._send_json(500, {"detail": "ZeroDivisionError: division by zero"})
            return
        if self.path == "/auth/profile":
            # Bug 4：即使带合法 Authorization 也错误返回 401
            self._send_json(401, {"detail": "Not authenticated"})
            return
        if self.path == "/orders":
            auth = self.headers.get("Authorization", "")
            if auth != "Bearer secret-tok-999":
                self._send_json(401, {"detail": "unauthorized"})
                return
            # Bug 6：登录后访问业务接口发现总额计算错误
            self._send_json(200, {"total": 99})
            return
        if self.path == "/echo":
            self._send_json(200, {"v": "hello"})
            return
        self._send_json(404, {"detail": "not found"})

    def do_POST(self) -> None:
        length = int(self.headers.get("Content-Length", "0") or "0")
        _ = self.rfile.read(length) if length > 0 else b""
        if self.path == "/login":
            self._send_json(200, {"access_token": "secret-tok-999", "user": "alice"})
            return
        self._send_json(404, {"detail": "not found"})


def _start_demo_server() -> tuple[ThreadingHTTPServer, str]:
    server = ThreadingHTTPServer(("127.0.0.1", 0), _DemoHandler)
    port = server.server_address[1]
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, f"http://127.0.0.1:{port}"


def _write_case_script(generated: Path, name: str, body: str) -> None:
    generated.mkdir(parents=True, exist_ok=True)
    (generated / name).write_text("# generated by aitest\n" + body, encoding="utf-8")


